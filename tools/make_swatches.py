# Turn painted images into seamless 512px tiles for the triplanar paint layer.
# Usage: python3 tools/make_swatches.py <out_dir> name=path[@x,y,w,h][:grey] ...
#   @x,y,w,h  crop box in source pixels (default: whole image)
#   :grey     keep only the brush-stroke detail around mid grey (a neutral detail map)
import sys, json, numpy as np
from PIL import Image, ImageFilter

def tileable(a):
    h, w = a.shape[:2]
    r = np.roll(np.roll(a, h // 2, 0), w // 2, 1)
    y = np.minimum(np.arange(h), np.arange(h)[::-1]) / (h / 2)
    x = np.minimum(np.arange(w), np.arange(w)[::-1]) / (w / 2)
    m = np.clip(np.minimum.outer(y, x) * 2.2, 0, 1)[..., None]
    m = m * m * (3 - 2 * m)
    return a * m + r * (1 - m)

out = sys.argv[1]; avgs = {}
for spec in sys.argv[2:]:
    name, rest = spec.split('=', 1)
    grey = rest.endswith(':grey'); rest = rest[:-5] if grey else rest
    path, _, box = rest.partition('@')
    im = Image.open(path).convert('RGB')
    if box:
        x, y, w, h = map(int, box.split(',')); im = im.crop((x, y, x + w, y + h))
    s = min(im.size); im = im.crop(((im.width - s) // 2, (im.height - s) // 2, (im.width - s) // 2 + s, (im.height - s) // 2 + s)).resize((512, 512), Image.LANCZOS)
    a = np.asarray(im, dtype=np.float32) / 255
    if grey:
        lo = np.asarray(im.filter(ImageFilter.GaussianBlur(24)), dtype=np.float32) / 255
        a = np.clip(0.5 + (a - lo) * 1.4, 0, 1)
        g = a.mean(axis=2, keepdims=True); a = g + (a - g) * 0.35
    else:
        # flatten big light/dark gradients (perspective, light rays) so the tile repeats evenly
        lo = np.asarray(im.filter(ImageFilter.GaussianBlur(64)), dtype=np.float32) / 255
        a = np.clip(a - lo + lo.mean(axis=(0, 1)), 0, 1)
    a = tileable(a)
    Image.fromarray((a * 255).astype(np.uint8)).save(f'{out}/{name}.jpg', quality=88)
    lin = np.where(a <= 0.04045, a / 12.92, ((a + 0.055) / 1.055) ** 2.4)
    avg = lin.reshape(-1, 3).mean(0)
    # stroke contrast: how much the tile varies around its average (the game boosts weak tiles)
    rel = (lin / np.maximum(avg, 1e-4)).mean(axis=2)
    avgs[name] = {'avg': [round(float(v), 4) for v in avg], 'std': round(float(rel.std()), 4)}
    print(name, avgs[name])
prev = {}
try: prev = json.load(open(f'{out}/avg.json'))
except Exception: pass
prev.update(avgs); json.dump(prev, open(f'{out}/avg.json', 'w'), indent=1)
# the game reads the list of tiles and their average (linear) colours from src/swatches.js
js = '// Generated by tools/make_swatches.py: painted tiles, their average linear colour and stroke contrast.\nexport const SWATCHES = ' + json.dumps({k: {'url': f'{out}/{k}.jpg', **v} for k, v in sorted(prev.items())}, indent=1) + ';\n'
open('src/swatches.js', 'w').write(js)
