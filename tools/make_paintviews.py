# Build src/paintviews.js + assets/paint/*.jpg from a cams.json and painted images.
# usage: python3 tools/make_paintviews.py <cams.json> <painted_dir> <prefix> name...
import json, sys, os
from PIL import Image
cams = json.load(open(sys.argv[1])); src = sys.argv[2]; prefix = sys.argv[3]; names = sys.argv[4:]
os.makedirs('assets/paint', exist_ok=True)
views = []
for n in names:
    im = Image.open(os.path.join(src, f'{prefix}{n}.png')).convert('RGB').resize((1280, 720), Image.LANCZOS)
    im.save(f'assets/paint/{n}.jpg', quality=85, optimize=True)
    c = cams[n]
    views.append({'name': n, 'url': f'assets/paint/{n}.jpg', 'cam': {'p': [round(v, 4) for v in c['p']], 'q': [round(v, 6) for v in c['q']], 'fov': c['fov'], 'aspect': round(c['aspect'], 6)}})
open('src/paintviews.js', 'w').write('// Generated by tools/make_paintviews.py: the camera each painting was made from.\nexport const PAINT_VIEWS = ' + json.dumps(views, indent=1) + ';\n')
print('ok', len(views))
